function detectLanguage(languages){ const first=languages?.[0]??''; return first.toLowerCase().startsWith('es')?'es':'en'; }
function browserLanguages(){
  if(typeof navigator==='undefined') return undefined;
  return navigator.languages?.length?navigator.languages:navigator.language?[navigator.language]:undefined;
}
